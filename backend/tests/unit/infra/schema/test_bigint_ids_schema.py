@pytest.mark.parametrize("table", EXPECTED_DEAL_CHILD_OBJECTS)
async def test_deal_child_constraints_and_indexes_are_named_after_deal_id(
    session: AsyncSession, table: str
) -> None:
    """제약 이름이 바뀌므로 Repository의 오류 매핑 상수도 이 이름을 따라야 한다."""

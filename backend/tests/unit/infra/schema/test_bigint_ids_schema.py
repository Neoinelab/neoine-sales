@pytest.mark.parametrize("table", SURROGATE_KEY_TABLES)
async def test_surrogate_keys_are_bigint_identity_by_default(
    session: AsyncSession, table: str
) -> None:
    """대리 키 테이블 20개의 id는 BIGINT IDENTITY BY DEFAULT(1, 1, 2^53-1)인 단일 PK다.

    테스트 코드: SC-014
    """
    # given: head를 적용한 임시 DB
    row = (await session.execute(text(IDENTITY), {"table": table})).one()
    # when: 테이블의 id 컬럼 정의와 PK를 읽는다
    primary_key = (await session.execute(text(PRIMARY_KEY), {"table": table})).all()

    # then: bigint identity BY DEFAULT, 최대 2^53-1, 시작 1, 증가 1, NOT NULL이고 PK는 id 하나다
    assert len(SURROGATE_KEY_TABLES) == 20
    assert row.data_type == "bigint"
    assert row.is_identity == "YES"
    assert row.identity_generation == "BY DEFAULT"  # 앱이 미리 받은 id도 넣을 수 있어야 한다
    assert int(row.identity_maximum) == MAX_ID == 9_007_199_254_740_991
    assert (int(row.identity_start), int(row.identity_increment)) == (1, 1)
    assert row.is_nullable == "NO"
    assert [tuple(r) for r in primary_key] == [("id", "bigint")]


async def test_deals_has_an_id_key_and_a_unique_deal_code(session: AsyncSession) -> None:
    """deals는 내부 id PK와 유일한 deal_code를 가져 같은 코드 두 번째 insert가 거부된다.

    테스트 코드: SC-018
    """
    # given: 고객 연락처 하나와 코드 20261016-A001인 Deal 하나
    customer = await insert_contact(session)
    await insert_deal(session, customer, code="20261016-A001")

    # when: 같은 코드로 Deal을 하나 더 넣으면 uq_deals_deal_code 위반이다
    with pytest.raises(IntegrityError, match="uq_deals_deal_code"):
        async with session.begin_nested():
            await insert_deal(session, customer, code="20261016-A001")

    # then: deal_code는 NOT NULL이고 deals에 pk·uq·코드 형식 제약이 있다
    deal_code = (
        await session.execute(text(COLUMN), {"table": "deals", "column": "deal_code"})
    ).one()
    assert deal_code[1] is True  # NOT NULL
    constraints = {
        r[0]
        for r in (
            await session.execute(
                text("select conname from pg_constraint where conrelid = 'deals'::regclass")
            )
        ).all()
    }
    assert {"pk_deals", "uq_deals_deal_code", "ck_deals_code_format"} <= constraints


async def test_deal_ids_are_assigned_by_the_database(session: AsyncSession) -> None:
    """id를 생략하고 넣은 deals 행은 DB가 1 이상 증가하는 id를 매긴다.

    테스트 코드: SC-019
    """
    # given: 고객 연락처 하나
    customer = await insert_contact(session)
    await insert_deal(session, customer, code="20261016-A001")
    await insert_deal(session, customer, code="20261016-A002")

    # when: id 없이 Deal 두 개를 넣는다
    ids = (await session.execute(text("select id from deals order by id"))).scalars().all()

    # then: 두 id는 1 이상 2^53-1 이하이고 두 번째가 더 크다
    assert len(ids) == 2
    assert 1 <= ids[0] < ids[1] <= MAX_ID


@pytest.mark.parametrize("table", DEAL_CHILD_TABLES)
async def test_deal_children_reference_deals_by_id_with_cascade(
    session: AsyncSession, table: str
) -> None:
    """Deal 소속 테이블은 deal_id로 deals.id를 CASCADE로 가리키고 deal_code 컬럼이 없다.

    테스트 코드: SC-020
    """
    # given: head를 적용한 임시 DB
    columns = {r[0] for r in (await session.execute(text(TABLE_COLUMNS), {"table": table})).all()}
    deal_id = (await session.execute(text(COLUMN), {"table": table, "column": "deal_id"})).one()
    # when: 테이블의 컬럼과 deals를 가리키는 FK를 읽는다
    fks = (await session.execute(text(DEAL_FOREIGN_KEY), {"table": table})).all()

    # then: deal_code 없음, deal_id는 bigint NOT NULL, FK는 deal_id -> deals.id CASCADE 하나
    assert "deal_code" not in columns
    assert (deal_id[0], deal_id[1]) == ("bigint", True)
    assert [(r[0].strip(), r[1], r[2], r[3]) for r in fks] == [("c", "deals", "deal_id", "id")]


async def test_deleting_a_deal_removes_its_children(session: AsyncSession) -> None:
    """Deal을 지우면 Deal 소속 테이블 6개의 행이 함께 지워진다.

    테스트 코드: SC-022
    """
    # given: Deal 하나와 그 Deal의 파트너 링크·BANT 선택·이력·Action·첨부·Comment 행
    owner = await insert_user(session, "owner-x")
    partner = await insert_contact(session, kind="partner", company="파트너")
    code = await insert_deal(session, await insert_contact(session), owner_user_id=owner)
    label = (
        await session.execute(text("select id from bant_labels where category = 'need' limit 1"))
    ).scalar_one()
    await insert_partner_link(session, code, partner)
    await insert_bant(session, code, "need", label)
    await insert_history(session, code, owner)
    await insert_action(session, code, owner)
    await insert_attachment(session, code, owner)
    await session.execute(
        text(
            "insert into deal_comments (id, deal_id, action_id, author_user_id, body, created_at,"
            " updated_at) select :id, id, null, :author, '본문', now(), now() from deals"
            " where deal_code = :code"
        ),
        {"id": new_id(), "author": owner, "code": code},
    )

    # when: 그 Deal을 지운다
    await session.execute(text("delete from deals where deal_code = :code"), {"code": code})

    counts = [
        (await session.execute(text(f"select count(*) from {table}"))).scalar_one()  # noqa: S608
        for table in DEAL_CHILD_TABLES
    ]
    # then: 소속 테이블 6개의 행 수가 모두 0이다
    assert counts == [0, 0, 0, 0, 0, 0]


async def test_meaningful_keys_are_kept(session: AsyncSession) -> None:
    """의미 있는 키 3개(로그인 실패·Deal BANT·비밀번호 해시)가 대리 키 대신 유지된다.

    테스트 코드: SC-015
    """
    # given: head를 적용한 임시 DB
    failures = (await session.execute(text(PRIMARY_KEY), {"table": "login_failures"})).all()
    bant = (await session.execute(text(PRIMARY_KEY), {"table": "deal_bant_labels"})).all()
    key_type = (
        await session.execute(text(COLUMN), {"table": "login_failures", "column": "key"})
    ).one()
    hashes = (await session.execute(text(PRIMARY_KEY), {"table": "user_password_hashes"})).all()
    # when: 세 테이블의 PK를 읽는다
    hash_identity = (
        await session.execute(
            text(
                "select is_identity from information_schema.columns"
                " where table_schema = 'public' and table_name = 'user_password_hashes'"
                " and column_name = 'user_id'"
            )
        )
    ).scalar_one()

    # then: key varchar(64) / (deal_id bigint, category) / user_id bigint(identity 아님)
    assert [tuple(r) for r in failures] == [("key", "character varying(64)")]
    assert key_type[0] == "character varying(64)"
    assert {r[0] for r in bant} == {"deal_id", "category"}  # 구분당 하나 = 키 자체
    assert dict(tuple(r) for r in bant)["deal_id"] == "bigint"
    assert [tuple(r) for r in hashes] == [("user_id", "bigint")]
    assert hash_identity == "NO"



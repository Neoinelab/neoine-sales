"""head 스키마의 id 규칙(AC-1~5): UUID 없음, 대리 키는 BIGINT IDENTITY, deals는 내부 id + 업무 키.

기본 PK는 `id BIGINT GENERATED BY DEFAULT AS IDENTITY (MAXVALUE 2^53-1)`다. 예외는 의미 있는
키뿐이다(로그인 실패 key, 단일 행 설정 id=1, BANT 선택의 복합 키). Deal 소속 테이블은
`deal_id`로 deals(id)를 CASCADE로 가리키고 `deal_code` 컬럼이 없다. 임시 DB의 head에서 돌며
세션은 테스트마다 롤백된다.
"""

